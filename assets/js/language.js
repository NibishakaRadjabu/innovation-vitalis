    const languageNames = {
        en: 'English',
        rw: 'Kinyarwanda',
        fr: 'Français',
    };
    const storageKey = 'innovatio-language';
    const supportedLanguages = ['en', 'rw', 'fr'];
    const originalText = new WeakMap();
    const translatedText = new WeakMap();
    let appliedLanguage = '';

    function translate(language) {
        document.documentElement.lang = language;
        const dictionary = translations[language] || {};
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (appliedLanguage === language && translatedText.get(node) === node.nodeValue) continue;
            const current = node.nodeValue || '';
            const leading = current.match(/^\s*/)?.[0] || '';
            const trailing = current.match(/\s*$/)?.[0] || '';
            const phrase = current.trim();
            const previousTranslation = translatedText.get(node);
            if (previousTranslation !== undefined && previousTranslation !== current) {
                originalText.set(node, phrase);
            }
            if (!originalText.has(node)) originalText.set(node, phrase);
            const source = originalText.get(node) ?? phrase;
            const result = language === 'en' ? source : (dictionary[source] || source);
            const value = `${leading}${result}${trailing}`;
            if (current !== value) {
                node.nodeValue = value;
                translatedText.set(node, value);
            } else {
                translatedText.set(node, current);
            }
        }
        appliedLanguage = language;

        document.querySelectorAll('[placeholder], [title], [aria-label]').forEach((element) => {
            ['placeholder', 'title', 'aria-label'].forEach((attribute) => {
                const value = element.getAttribute(attribute);
                if (!value) return;
                const key = `data-language-original-${attribute}`;
                if (!element.hasAttribute(key)) element.setAttribute(key, value);
                const source = element.getAttribute(key);
                element.setAttribute(attribute, language === 'en' ? source : (dictionary[source] || source));
            });
        });

        const title = document.querySelector('title');
        if (title) {
            if (!title.dataset.languageOriginal) title.dataset.languageOriginal = title.textContent || '';
            const source = title.dataset.languageOriginal;
            title.textContent = language === 'en' ? source : (dictionary[source] || source);
        }
    }

    function installSelector() {
        if (document.querySelector('.language-selector')) return;
        const wrapper = document.createElement('label');
        wrapper.className = 'language-selector';
        wrapper.innerHTML = '<span class="language-selector-label">Language</span>';
        const select = document.createElement('select');
        select.setAttribute('aria-label', 'Choose language');
        Object.entries(languageNames).forEach(([value, name]) => {
            const option = document.createElement('option');
            option.value = value;
            option.textContent = name;
            select.appendChild(option);
        });

        let current = 'en';
        try {
            const saved = localStorage.getItem(storageKey);
            if (supportedLanguages.includes(saved)) current = saved;
        } catch {
            current = 'en';
        }
        select.value = current;
        wrapper.appendChild(select);
        document.body.appendChild(wrapper);
        translate(current);

        select.addEventListener('change', () => {
            const language = supportedLanguages.includes(select.value) ? select.value : 'en';
            try {
                localStorage.setItem(storageKey, language);
            } catch {
                // Keep the selected language for this page even when storage is unavailable.
            }
            translate(language);
        });

        const observer = new MutationObserver((records) => {
            const language = select.value;
            records.forEach((record) => {
                record.addedNodes.forEach((added) => {
                    if (added.nodeType === Node.TEXT_NODE) {
                        if (!originalText.has(added)) originalText.set(added, (added.nodeValue || '').trim());
                    } else if (added.nodeType === Node.ELEMENT_NODE) {
                        added.querySelectorAll?.('*').forEach((element) => {
                            element.childNodes.forEach((child) => {
                                if (child.nodeType === Node.TEXT_NODE && !originalText.has(child)) {
                                    originalText.set(child, (child.nodeValue || '').trim());
                                }
                            });
                        });
                    }
                });
            });
            translate(language);
        });
        observer.observe(document.body, { childList: true, subtree: true });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', installSelector, { once: true });
    } else {
        installSelector();
    }
